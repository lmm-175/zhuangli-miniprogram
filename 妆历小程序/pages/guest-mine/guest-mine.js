/**
 * 「我的」（约妆端）· 约妆端 tabBar 第 3 格（2026-10-01 第二十一处新增）。
 *
 * 🔴 这一页是**用户点名要的**，原话：
 *    「用户端预约过的妆娘是一个页面，我的是一个页面，你懂吗，
 *      不要放在同一个页面里面」
 *    —— 原先这两块挤在约妆首页（`pages/guest-home/`）的上下两段里。
 *    改法不是「把两段分开画」，是**给约妆端一条和妆师端一样的底部条**。
 *    两块内容各回各页 —— 规矩 37：搬家，⛔ 不是复制一份。
 *    于是 `pages/guest-home/` 整页退役（⛔ 别把它加回来：首页那两段
 *    正是被投诉的形状）。
 *
 * 📌 同日第二轮（用户原话「底栏变成三个，把我的预约也放进去，「我的」里面
 *    只有切换身份 反馈 设置」）：约妆端底部条 **2 格 → 3 格**
 *    （我约过的妆娘 / 我的预约 / 我的），本页退到第 3 格，
 *    「我的预约」升成 tab 2 ⇒ 本页那一行 `goMyBookings` **整个删掉**。
 *    ⚠️ 删的是**重复入口**（落点变成 tab 了），⛔ 不是删功能。
 *
 * ⚠️ 顾客**没有「资料」这个东西**（妆历里没有顾客账号，只有她提交过的单），
 *    所以这一页⛔ 不照抄妆师端「我的」那张头像卡 ——
 *    妆娘才是要维护昵称/城市/风格/简介的那个人，她的那张卡在 `pages/mine/`。
 *    抄过来只会得到一张永远不填的空白资料卡。
 *
 * ⚠️ 三行都必须**真的跳得动**：第十四处那两行「有响应、但不跳页面」
 *    （只弹 toast）就是这个项目栽过的地方，README 第 14 / 26 条。
 */
const { syncTabBar } = require('../../utils/tabbar')

Page({
  onShow() {
    // 第一行就把底部那条点亮（本页是约妆端第 3 格）—— 见 utils/tabbar.js
    syncTabBar(this)
  },

  /* 切换身份 → 回到角色选择。
     ⚠️ 走 navigateTo，和妆师端 `pages/mine/mine.js` 那条**逐字一样**（规矩 11）：
        role-select 是普通页，在那边选完了会用 `wx.switchTab` 换掉整条底部条。 */
  switchRole() {
    wx.navigateTo({ url: '/pages/role-select/role-select' })
  },

  /* 问题反馈 → 和妆师端「我的」那一行**同一个页面**（pages/feedback/）。
     ⚠️ 那一页的「确认反馈」是真写云端的（第十九处），失败会当场说没发出去；
        这里只负责把人送过去，⛔ 不在这里再判一遍配置。 */
  goFeedback() {
    wx.navigateTo({ url: '/pages/feedback/feedback' })
  },

  /* 设置 → 和妆师端「我的」那一行**同一个页面**（pages/settings/，规矩 37）。
     ⚠️ 那一页自己知道当前角色：顶上那个微信号开关**只对妆娘画**
        （用户原话「顾客没有展示微信号的开关，顾客不展示」）。
        ⇒ 这里⛔ 不要传参、也不要复制一个顾客专用的设置页。 */
  goSettings() {
    wx.navigateTo({ url: '/pages/settings/settings' })
  }
})

/* 🔴 云环境 ID（用户 2026-09-30 给的真环境，**不是** AppID，别混）。
   ⛔ 别在这里写 AppID / AppSecret / 任何密钥 —— 这个文件会进代码仓库，
      而小程序代码包里的东西是可被下载解包的。环境 ID 不是密钥（它要在
      客户端用），但密钥是。 */
const CLOUD_ENV = 'cloud1-d0gir0d3e31de18ba'

/* 配好了没有。⚠️ 判据是【非空】，⛔ 不是「wx.cloud 存在」——
   开发者工具里 wx.cloud 一直都在，它在不代表这个项目开了云环境。 */
function isConfigured() {
  return String(CLOUD_ENV || '').length > 0
}

/* 初始化。⚠️ 只在配好了的时候才真调 wx.cloud.init ——
   拿空串或占位符去调，控制台会刷一片红色报错，而人看到报错会以为
   「云这一块大概在跑吧」，反而比不调更误导。
   ⚠️ 返回 true/false 而不是 undefined：调用方（app.js）将来若要按它分支，
      不该靠"侧面猜"。 */
function initCloud() {
  if (!isConfigured()) {
    // ⚠️ 这里【故意】只在控制台说，⛔ 不弹 toast：这一句是给开发者看的，
    //    而 wx.cloud.init 是 App 启动时调的，那一刻屏幕上还没有页面。
    console.warn('[cloud] 云环境没配（utils/cloud.js 的 CLOUD_ENV 是空的）：'
      + '反馈会发不出去。配置步骤见 README §6。')
    return false
  }
  if (!wx.cloud) {
    // 基础库太老（wx.cloud 要 ≥ 2.2.3）。也是给开发者看的。
    console.warn('[cloud] 这个基础库没有 wx.cloud，反馈发不出去。')
    return false
  }
  wx.cloud.init({ env: CLOUD_ENV, traceUser: true })
  return true
}

module.exports = { CLOUD_ENV, isConfigured, initCloud }

// 备案「小程序备注」核验 v2 —— 用户提供的被驳回原文 vs 改写稿
const GROUPS = {
  '交易类': ['预约', '预订', '下单', '订单', '接单', '约妆'],
  '角色类': ['顾客', '客户', '客人', '用户'],
  '资金类': ['金额', '价格', '报价', '费用', '收费', '付款', '支付', '定金', '尾款', '资金', '收款', '结算', '抽成', '充值', '购买'],
  '主体类': ['平台', '入驻', '商家', '店铺', '撮合', '中介'],
  '经营类': ['营业', '经营', '营销', '推广', '获客', '服务', '套餐', '优惠'],
  '内容类': ['作品', '评价', '评分', '妆位', '档期', '接妆'],
  '备案追加': ['企业', '公司', '商业', '交易', '化妆师', '客服', '行业', '从业', '商家', '工作室', '推广位'],
};
const ALL = [...new Set(Object.values(GROUPS).flat())];

const CANDIDATES = {
  '★ 你提交的原文(107字)': '妆历是一个给化妆师自己用的时间安排小工具。把一天按时间段排好，写下每段做什么；排完随时能改，打开就能记，不用纸笔也不用表格。需要时可以把排好的安排分享出去，对方点开就能看到，不用另外装东西。所有记录都留在自己手上。',

  'H 新·主版(≈110字)': '本小程序是一个个人自用的时间安排记录小工具。把一天按时间段排好，写下每段做什么；排完随时能改，打开就能记，不用纸笔也不用表格。需要时可以把排好的安排分享出去，对方点开就能看到。所有记录都留在自己手上。',
  'I 新·保守版(52字)': '本小程序为个人自用的时间安排记录小工具，用于记录和查看自己的日常安排，所有记录只保存在自己这里，不对外公开。',
  'J 新·极简(32字)': '个人自用的时间安排记录小工具，用于记录自己的日常安排。',
};

for (const [name, text] of Object.entries(CANDIDATES)) {
  const hits = ALL.filter(w => text.includes(w));
  const detail = Object.entries(GROUPS)
    .map(([g, ws]) => [g, ws.filter(w => hits.includes(w))])
    .filter(([, ws]) => ws.length)
    .map(([g, ws]) => `${g}(${[...new Set(ws)].join('/')})`)
    .join(' ');
  console.log(`${name.padEnd(24, ' ')} 字数=${String([...text].length).padStart(3, ' ')}  命中=${String(hits.length).padStart(2, ' ')}  ${detail}`);
}
